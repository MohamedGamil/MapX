// Embeds src/arch/presets/*.jsonc in src/arch/presets/index.ts (M5-17). tsup does not bundle
// (bundle: false) and the bun binary has no source tree, so the shipped presets live in a module;
// the .jsonc files stay the readable source. tests/arch-init.test.ts fails when the two differ.
// Usage: npx tsx scripts/gen-arch-presets.ts [--check]
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

const DIR = resolve(import.meta.dirname, '..', 'src', 'arch', 'presets');

/** The module text for the .jsonc files in `dir`, sorted by id. */
export function presetModule(dir = DIR): string {
  const ids = readdirSync(dir).filter((f) => f.endsWith('.jsonc')).map((f) => f.slice(0, -'.jsonc'.length)).sort();
  const entries = ids.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(readFileSync(join(dir, `${id}.jsonc`), 'utf8'))},`);
  return [
    '// GENERATED by scripts/gen-arch-presets.ts from src/arch/presets/*.jsonc: edit those, then run',
    '// `npx tsx scripts/gen-arch-presets.ts`. The shipped presets (`mapx:preset/<id>`, M5-17), as JSONC text.',
    'export const PRESET_TEXTS: Readonly<Record<string, string>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(import.meta.filename)) {
  const text = presetModule();
  const out = join(DIR, 'index.ts');
  if (process.argv.includes('--check')) {
    if (readFileSync(out, 'utf8') !== text) {
      console.error('src/arch/presets/index.ts is out of date: run `npx tsx scripts/gen-arch-presets.ts`.');
      process.exit(1);
    }
  } else {
    writeFileSync(out, text);
    console.log(`Wrote ${out}.`);
  }
}
