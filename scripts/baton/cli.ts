// BATON plan CLI. Every status change goes through `transition`, which re-validates the plan.
//   npx tsx scripts/baton/cli.ts validate | ready | status | critical-path | report | handoff
//   npx tsx scripts/baton/cli.ts transition <ID> <STATUS> [evidence.json] [--owner NAME]
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { execFileSync } from 'node:child_process';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
  blockers,
  criticalPath,
  handoff,
  ready,
  resourceSchedule,
  transition,
  validate,
} from './model.ts';
import type { Evidence, Plan, Requirement, Status } from './model.ts';
import { checkArtifacts } from './artifacts.ts';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '../..');
const dir = resolve(root, 'docs/baton');
const path = resolve(dir, 'TASKS.json');
const requirementsPath = resolve(dir, 'REQUIREMENTS.json');
let plan = JSON.parse(readFileSync(path, 'utf8')) as Plan;
const requirements = existsSync(requirementsPath)
  ? (JSON.parse(readFileSync(requirementsPath, 'utf8')) as Requirement[])
  : [];

function checked() {
  validate(plan, requirements);
  checkArtifacts(plan, root);
}
function git(args: string[]) {
  return execFileSync('git', args, { cwd: root, encoding: 'utf8' }).trim();
}
function revision() {
  return (
    `${git(['rev-parse', '--abbrev-ref', 'HEAD'])}@${git(['rev-parse', 'HEAD'])}` +
    (git(['status', '--porcelain']) ? ' (uncommitted changes)' : '')
  );
}
const open = (status: Status) => !['DONE', 'DEFERRED', 'CANCELLED'].includes(status);

function reports() {
  const cp = criticalPath(plan);
  const baseline = criticalPath(plan, false);
  const schedule = resourceSchedule(plan);
  const sum = (key: 'min' | 'expected' | 'max') =>
    plan.tasks.filter((t) => open(t.status)).reduce((s, t) => s + t.estimate[key], 0);
  const timings =
    '| Task | ES | EF | LS | LF | Slack |\n|---|---:|---:|---:|---:|---:|\n' +
    cp.times
      .filter((t) => t.duration > 0)
      .map(
        (t) =>
          `| ${t.id} | ${t.earliestStart} | ${t.earliestFinish} | ${t.latestStart} | ${t.latestFinish} | ${t.slack} |`,
      )
      .join('\n');
  writeFileSync(
    resolve(dir, 'CRITICAL_PATH.md'),
    `# Critical path\n\nGenerated by \`npm run plan:report\` from TASKS.json. Dates are conditional effort conversions, not commitments; gate waits are excluded. Epics must be decomposed before execution.\n\nRemaining longest dependency path: **${cp.duration}h** (full-plan path: ${baseline.duration}h).\n\n${cp.path.join(' → ') || 'none'}\n\nRemaining effort min/expected/max: **${sum('min')} / ${sum('expected')} / ${sum('max')}h**. Capacity: ${plan.capacity.engineers} engineer(s) × ${plan.capacity.productiveHoursPerWeek} h/week → **${schedule.weeks.toFixed(1)} weeks**, conditional finish **${schedule.conditionalDate}** (as of ${schedule.forecastAsOf}).\n\n## Open items and blockers\n${plan.tasks
      .filter((t) => open(t.status))
      .map((t) => `- ${t.id} (${t.status}): ${blockers(plan, t).join('; ') || 'prerequisites satisfied'}`)
      .join('\n')}\n\n## Remaining CPM timings (hours)\n${timings}\n`,
  );
  mkdirSync(resolve(dir, 'reports'), { recursive: true });
  writeFileSync(
    resolve(dir, 'reports/critical-path.json'),
    JSON.stringify({ baseline, remaining: cp, resourceSchedule: schedule }, null, 2) + '\n',
  );
  const eligible = new Set(ready(plan).map((t) => t.id));
  writeFileSync(
    resolve(dir, 'ITERATION_QUEUE.md'),
    '# Execution queue\n\nGenerated by `npm run plan:report`. Readiness is recomputed from dependencies, gates and blocking conditions; epics require decomposition. One active iteration per owner.\n\n' +
      plan.tasks
        .filter((t) => open(t.status))
        .map(
          (t) =>
            `- **${t.id}** ${t.status}${eligible.has(t.id) && t.status !== 'READY' ? ' (promotable)' : ''} [${t.priority}] — ${t.title}; ${blockers(plan, t).join('; ') || 'prerequisites satisfied'}`,
        )
        .join('\n') +
      '\n',
  );
  const edges = new Set(
    plan.tasks.flatMap((t) =>
      t.dependencies
        .filter((d) => d.id.split('-')[0] !== t.milestone)
        .map((d) => `  ${d.id.split('-')[0]} --> ${t.milestone}`),
    ),
  );
  writeFileSync(
    resolve(dir, 'DEPENDENCIES.md'),
    '# Dependencies\n\nGenerated by `npm run plan:report`. The task DAG in TASKS.json is authoritative; milestone aggregation can hide independent streams. Optional dependencies are advisory.\n\n```mermaid\nflowchart LR\n' +
      [...edges].join('\n') +
      '\n```\n\n' +
      plan.tasks
        .map(
          (t) =>
            `- ${t.id} ← ${t.dependencies.map((d) => `${d.id} (${d.type})`).join(', ') || 'none'}${t.approvalGate ? `; gate ${t.approvalGate}` : ''}`,
        )
        .join('\n') +
      '\n',
  );
  let roadmap =
    '# Master roadmap\n\nGenerated by `npm run plan:report` from TASKS.json. Each task has acceptance criteria and registered verification commands there; iteration specs live in `docs/baton/iterations/`.\n\n';
  let forecast =
    '# Milestones\n\nGenerated by `npm run plan:report`. A milestone is complete only when every task in it is DONE.\n\n| Milestone | Release | Status | Tasks done | Expected effort (h) | Dependency finish (h) | Resource finish (weeks) |\n|---|---|---|---:|---:|---:|---:|\n';
  for (const m of plan.milestones) {
    const tasks = plan.tasks.filter((t) => t.milestone === m.id);
    if (!tasks.length) continue;
    const hours = tasks.reduce((s, t) => s + t.estimate.expected, 0);
    const end = Math.max(...tasks.map((t) => cp.times.find((x) => x.id === t.id)!.earliestFinish));
    const resourceEnd = Math.max(
      ...tasks.map((t) => schedule.assignments.find((x) => x.id === t.id)!.finish),
    );
    const done = tasks.filter((t) => t.status === 'DONE').length;
    const status =
      done === tasks.length
        ? 'DONE'
        : tasks.some((t) => !['BACKLOG', 'BLOCKED', 'READY'].includes(t.status))
          ? 'IN_PROGRESS'
          : 'PLANNED';
    forecast += `| ${m.id} ${m.title} | ${m.release ?? '—'} | ${status} | ${done}/${tasks.length} | ${hours} | ${end} | ${(resourceEnd / plan.capacity.productiveHoursPerWeek).toFixed(1)} |\n`;
    roadmap +=
      `## ${m.id} — ${m.title}${m.release ? ` (${m.release})` : ''}\n\n${m.goal}\n\n` +
      tasks
        .map(
          (t) =>
            `- **${t.id}** ${t.title} — ${t.status}, ${t.priority}, ${t.estimate.expected}h${t.legacyId ? ` (legacy ${t.legacyId})` : ''}; depends on ${t.dependencies.map((d) => d.id).join(', ') || 'nothing'}.`,
        )
        .join('\n') +
      '\n\n';
  }
  writeFileSync(resolve(dir, 'MASTER_ROADMAP.md'), roadmap);
  writeFileSync(resolve(dir, 'MILESTONES.md'), forecast);
  for (const t of plan.tasks)
    t.criticalPath = open(t.status) && cp.times.find((x) => x.id === t.id)!.slack === 0;
  writeFileSync(path, JSON.stringify(plan, null, 2) + '\n');
}

try {
  checked();
  const command = process.argv[2] ?? 'status';
  switch (command) {
    case 'validate':
      console.log(
        `Valid: ${plan.tasks.length} tasks, ${plan.milestones.length} milestones, ${requirements.length} requirements, no cycles; gate/evidence/readiness invariants hold.`,
      );
      break;
    case 'ready':
      console.log(
        ready(plan)
          .map((t) => `${t.id} [${t.priority}] ${t.status} ${t.title}`)
          .join('\n') || 'No eligible tasks.',
      );
      break;
    case 'status':
      console.log(plan.tasks.map((t) => `${t.id} ${t.status} ${t.title}`).join('\n'));
      break;
    case 'critical-path':
      console.log(
        JSON.stringify({ remaining: criticalPath(plan), resource: resourceSchedule(plan) }, null, 2),
      );
      break;
    case 'handoff': {
      const packet = handoff(plan, revision());
      writeFileSync(resolve(dir, 'HANDOFF.md'), packet);
      console.log(packet);
      break;
    }
    case 'report':
      reports();
      console.log('Updated roadmap, milestones, dependencies, queue and critical-path reports.');
      break;
    case 'transition': {
      const args = process.argv.slice(3);
      const ownerAt = args.indexOf('--owner');
      const owner = ownerAt >= 0 ? args.splice(ownerAt, 2)[1] : undefined;
      const [id, status, evidenceFile] = args;
      if (!id || !status) throw new Error('Usage: transition <ID> <STATUS> [evidence.json] [--owner NAME]');
      const evidence = evidenceFile
        ? (JSON.parse(readFileSync(resolve(root, evidenceFile), 'utf8')) as Evidence[])
        : [];
      plan = transition(plan, id, status as Status, evidence, undefined, owner);
      checked();
      writeFileSync(path, JSON.stringify(plan, null, 2) + '\n');
      console.log(`${id} → ${status}`);
      break;
    }
    default:
      throw new Error(`Unknown command ${command}`);
  }
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
