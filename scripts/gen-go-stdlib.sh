#!/usr/bin/env bash
# Generates src/core/manifests/go-stdlib.ts (M5-23): the importable packages of Go's standard
# library, the union of `go list std` over several Go releases and every target. It runs each
# release's official Docker image (golang:<version>-alpine), or a local `go` when GO_LOCAL=1 (one
# release only). The list does not depend on the Go that runs MapX, and nothing else is read.
#
#   scripts/gen-go-stdlib.sh [version ...]      default: 1.22 1.23 1.24 1.25 1.26 1.27
#
# `go list std` lists only the packages that build for the current target, so each release is
# listed for every GOOS of `go tool dist list` (one GOARCH each: js/wasm gives syscall/js), with
# cgo off and on (on gives runtime/cgo) (review of M5-23).
#
# Kept: the packages a program may import. Dropped: `vendor/…` (the standard library's own vendored
# copies of golang.org/x) and every path with an `internal` element (importable only from inside
# the standard library). A package that left the library in a later release stays listed.
set -euo pipefail
cd "$(dirname "$0")/.."
versions=("$@")
[ ${#versions[@]} -eq 0 ] && versions=(1.22 1.23 1.24 1.25 1.26 1.27)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
# Run in the toolchain: the union over targets, then GOVERSION on stderr.
list='
for target in $(go tool dist list | awk -F/ "!seen[\$1]++"); do
  for cgo in 0 1; do
    GOOS=${target%/*} GOARCH=${target#*/} CGO_ENABLED=$cgo go list std 2>/dev/null || true
  done
done | sort -u
go env GOVERSION >&2
'
sources=()
for v in "${versions[@]}"; do
  if [ "${GO_LOCAL:-}" = 1 ]; then
    sh -c "$list" > "$tmp/$v.txt" 2> "$tmp/$v.version"
  else
    # One image at a time; an image this run pulled is removed after use (each is a few hundred MB).
    image="golang:$v-alpine"
    pulled=0
    docker image inspect "$image" > /dev/null 2>&1 || pulled=1
    docker run --rm "$image" sh -c "$list" > "$tmp/$v.txt" 2> "$tmp/$v.version"
    [ "$pulled" = 1 ] && docker rmi "$image" > /dev/null
  fi
  sources+=("$(tail -n 1 "$tmp/$v.version")")
done
cat "$tmp"/*.txt | grep -v '^vendor/' | grep -Ev '(^|/)internal(/|$)' | sort -u > "$tmp/all.txt"
{
  echo '// Generated by scripts/gen-go-stdlib.sh (M5-23); do not edit. The importable packages of Go'"'"'s'
  echo '// standard library: the union of `go list std` of the releases below, for every GOOS with cgo off'
  echo '// and on, without `vendor/` and `internal` packages.'
  echo "export const GO_STDLIB_SOURCE = '$(IFS=,; echo "${sources[*]}" | sed 's/,/, /g')';"
  echo ''
  echo '/** One package import path per entry, sorted. */'
  echo 'export const GO_STDLIB: readonly string[] = ['
  sed "s/.*/  '&',/" "$tmp/all.txt"
  echo '];'
} > src/core/manifests/go-stdlib.ts
echo "$(wc -l < "$tmp/all.txt") packages from ${sources[*]}"
