#!/usr/bin/env python3
"""Generates src/core/manifests/python-stdlib.ts, the static list of the Python standard library's
top-level modules that external-reference attribution classifies as builtins (M5-22).

    python3.10 scripts/gen-python-stdlib.py dump > py310.json            (once per Python binary, 3.10+)
    python3 scripts/gen-python-stdlib.py header v3.14.0 > h314.json       (once per CPython tag)
    python3 scripts/gen-python-stdlib.py merge py310.json h310.json ... > src/core/manifests/python-stdlib.ts

`dump` reads the running Python's `sys.stdlib_module_names` (Python 3.10+): every top-level module of
the standard library, pure Python or built in, whether or not this build has it (`winreg`, `msvcrt`).
`header` reads the list that same attribute is built from, `Python/stdlib_module_names.h` of a CPython
release tag (https://github.com/python/cpython/blob/<tag>/Python/stdlib_module_names.h), so versions
not installed here are covered; it is read as text, never compiled. `merge` writes the union, with
its sources: a module that a later version removed (`distutils`, `imp`, `cgi`) stays a builtin, since
code that imports it targets an older Python.
"""
import json
import re
import sys
import urllib.request

HEADER_URL = 'https://raw.githubusercontent.com/python/cpython/{tag}/Python/stdlib_module_names.h'


def dump() -> None:
    names = getattr(sys, 'stdlib_module_names', None)
    if names is None:
        sys.exit('sys.stdlib_module_names needs Python 3.10 or later')
    version = '.'.join(str(n) for n in sys.version_info[:3])
    print(json.dumps({'source': f'sys.stdlib_module_names of Python {version}', 'modules': sorted(names)}))


def header(tag: str, path: str | None = None) -> None:
    if path:
        with open(path, encoding='utf-8') as f:
            text = f.read()
    else:
        with urllib.request.urlopen(HEADER_URL.format(tag=tag), timeout=60) as r:
            text = r.read().decode('utf-8')
    body = text[text.index('_Py_stdlib_module_names[]'):]
    modules = sorted(set(re.findall(r'^"([A-Za-z_][A-Za-z0-9_]*)",$', body, re.M)))
    if len(modules) < 200:
        sys.exit(f'{tag}: only {len(modules)} modules read; not a stdlib_module_names.h')
    print(json.dumps({'source': f'Python/stdlib_module_names.h of CPython {tag}', 'modules': modules}))


def merge(paths: list[str]) -> None:
    sources: list[str] = []
    modules: set[str] = set()
    for path in paths:
        with open(path, encoding='utf-8') as f:
            data = json.load(f)
        sources.append(data['source'])
        modules.update(data['modules'])
    source = '; '.join(sources) + ' (union)'
    names = sorted(modules)
    lines = [
        '// Generated by scripts/gen-python-stdlib.py (M5-22); do not edit. Regenerate with the commands in that script.',
        f'// Source: {source}: {len(names)} top-level modules.',
        '',
        "/** Where the list comes from: the Python versions read and the CPython tags whose stdlib_module_names.h was read. */",
        f'export const PYTHON_STDLIB_SOURCE = {json.dumps(source)};',
        '',
        '/** The top-level modules of the Python standard library, space-separated (`sys.stdlib_module_names`, union of the sources). */',
        'export const PYTHON_STDLIB_MODULES =',
    ]
    chunk: list[str] = []
    out: list[str] = []
    for name in names:
        if sum(len(n) + 1 for n in chunk) + len(name) > 100:
            out.append(' '.join(chunk))
            chunk = []
        chunk.append(name)
    out.append(' '.join(chunk))
    for i, line in enumerate(out):
        sep = ' ' if i < len(out) - 1 else ''
        end = ' +' if i < len(out) - 1 else ';'
        lines.append(f"  '{line}{sep}'{end}")
    print('\n'.join(lines))


if __name__ == '__main__':
    if len(sys.argv) < 2 or sys.argv[1] not in ('dump', 'header', 'merge'):
        sys.exit(__doc__)
    if sys.argv[1] == 'dump':
        dump()
    elif sys.argv[1] == 'header':
        header(sys.argv[2], sys.argv[3] if len(sys.argv) > 3 else None)
    else:
        merge(sys.argv[2:])
